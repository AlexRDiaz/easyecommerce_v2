import 'package:flutter/material.dart';

class TextStylesSystem {
  
  TextStyle ralewayStyle(fontSizeP, fontWeightP, colorP) {
    return TextStyle(
        fontFamily: 'Raleway',
        fontSize: fontSizeP,
        fontWeight: fontWeightP,
        color: colorP);
  }

  TextStyle montserratStyle(fontSizeP, fontWeightP, colorP) {
    return TextStyle(
        fontFamily: 'Montserrat',
        fontSize: fontSizeP,
        fontWeight: fontWeightP,
        color: colorP);
  }


}
